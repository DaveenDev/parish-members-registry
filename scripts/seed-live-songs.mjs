// Puts the real sample songs (scripts/sample-songs.mjs: public-domain hymns,
// Latin texts and prayer texts used at Mass, never the demo songs written
// for training) on the LIVE site's Downloads page, published. A song whose
// title is already there is left alone, so running it again adds nothing.
// Needs 0096 and 0097 on live and the Supabase CLI signed in.
//
//   npm run db:seed-live-songs
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { SONGS, isDemoSong, songValues } from './sample-songs.mjs';

const LIVE = 'rmlkowkbonbrtaqocsvo';
const songs = SONGS.filter((s) => !isDemoSong(s));

const sql = `-- Generated by scripts/seed-live-songs.mjs.
insert into songs (title, composer, language, categories, note, lyrics, published)
select v.title, v.composer, v.language, v.categories, v.note, v.lyrics, v.published
from (values
${songValues(songs).join(',\n')}
) as v(title, composer, language, categories, note, lyrics, published)
where not exists (select 1 from songs s where lower(s.title) = lower(v.title));
`;
const file = 'supabase/seed/live-songs.sql';
fs.writeFileSync(file, sql);

execFileSync('npx', ['supabase', 'db', 'query', '-f', file, '--project-ref', LIVE, '--linked'], { stdio: 'pipe', shell: true });
fs.rmSync(file);
console.log(`Live site: the ${songs.length} real sample songs are on Downloads (any already there were left as they were).`);
